const B = require("./check.js");
const rules = require("./rules.json");
const fs = require("fs");
let fail = 0;
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "ok  " : "FAIL", name, ok ? "" : JSON.stringify(got) + " != " + JSON.stringify(want)); };
const now = "2026-10-27";
const { rows, skipped } = B.parse(fs.readFileSync(__dirname + "/../sample/projects.sample.json", "utf8"));
eq("sample has 5 projects", [rows.length, skipped.length], [5, 0]);
const res = B.check(rows, rules, now);
const by = Object.fromEntries(res.map((r) => [r.name, r]));
eq("free with a recent dump and restore test: ok", by["prototype-notes"].level, "ok");
eq("free worst case = days since dump", by["prototype-notes"].worstCase.label, "7 days (since the last manual dump)");
eq("free without any dump: bad", [by["old-experiment"].level, by["old-experiment"].worstCase.hours], ["bad", null]);
eq("free with storage files and no file backup is flagged", by["old-experiment"].issues.some((i) => /Storage files/.test(i.text)), true);
eq("pro daily: worst case 24h", by["team-wiki"].worstCase.hours, 24);
eq("pro with a recent restore test but no file backup: warn, one issue", [by["team-wiki"].level, by["team-wiki"].issues.length], ["warn", 1]);
eq("a 47-day-old restore test is NOT flagged (limit is 90)", by["team-wiki"].issues.some((i) => /restore test/.test(i.text)), false);
eq("no restore test on record is flagged", B.check([{ name: "x", plan: "pro" }], rules, now)[0].issues.some((i) => /no restore test/.test(i.text)), true);
eq("pitr on micro compute: bad (docs: needs small)", by["customer-portal"].level, "bad");
eq("pitr worst case = 2 minutes", by["billing-core"].worstCase.label, "about 2 minutes");
eq("team with pitr, medium, tested, files backed up: ok (info only)", [by["billing-core"].level, by["billing-core"].issues.map((i) => i.level)], ["ok", ["info"]]);
eq("pitr cost: 7d + 14d = 100 + 200", B.pitrCost(res, rules), { total: 300, projects: 2 });
eq("restore test older than 90 days warns", B.check([{ name: "x", plan: "pro", lastRestoreTestAt: "2026-06-01" }], rules, now)[0].issues.some((i) => /days old/.test(i.text)), true);
eq("pitr on free is bad", B.check([{ name: "x", plan: "free", pitr: true, lastDumpAt: "2026-10-27" }], rules, now)[0].level, "bad");
eq("old dump on free warns", B.check([{ name: "x", plan: "free", lastDumpAt: "2026-10-01", lastRestoreTestAt: "2026-10-01" }], rules, now)[0].level, "warn");
eq("bad json rejected", (() => { try { B.parse("{x"); } catch (e) { return /Not valid JSON/.test(e.message); } })(), true);
eq("row without plan skipped and reported", B.parse('[{"name":"a"},{"name":"b","plan":"pro"}]').skipped.length, 1);
process.exit(fail ? 1 : 0);
